// Bundles src/ into one Apps Script file: apps-script/Code.js.
import { build } from 'esbuild';

const footer = `
function onOpen(e) { return BreadClub.app.onOpen(e); }
function onEdit(e) { return BreadClub.app.onEdit(e); }
function onFormSubmitTrigger() { return BreadClub.app.refresh(); }
function dailyRefresh() { return BreadClub.app.refresh(); }
function refreshNow() { BreadClub.app.refresh(); SpreadsheetApp.getActive().toast('Bread Club: refreshed'); }
function setupBreadClub() {
  var added = BreadClub.app.setup();
  SpreadsheetApp.getUi().alert('Bread Club is set up.' + (added.length ? ' Added columns: ' + added.join(', ') : ''));
}
`;

await build({
  entryPoints: ['src/gas-entry.js'],
  bundle: true,
  format: 'iife',
  globalName: 'BreadClub',
  target: 'es2019',
  outfile: 'apps-script/Code.js',
  banner: { js: '// GENERATED by `npm run build` from src/. Do not edit by hand.' },
  footer: { js: footer },
});
console.log('Built apps-script/Code.js');
