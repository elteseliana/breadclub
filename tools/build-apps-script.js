'use strict';
/*
 * Combines the order rules and the Sheets adapter into one file that Eliana pastes
 * into the Google Apps Script editor (Extensions > Apps Script > Code.gs).
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const parts = ['site/assets/js/logic.js', 'apps-script/src/server.js', 'apps-script/src/Code.js'];
const header = '// The Bread Club order backend. GENERATED by `npm run build:apps-script`, do not edit by hand.\n' +
  '// Paste this whole file into Code.gs in the Apps Script editor. Source: ' + parts.join(', ') + '\n\n';
const body = parts.map((p) => '// ---- ' + p + ' ----\n' + fs.readFileSync(path.join(root, p), 'utf8')).join('\n');
const out = path.join(root, 'apps-script', 'dist', 'Code.gs');
fs.writeFileSync(out, header + body);

// Sanity check: the combined file must at least parse and define the entry points.
const vm = require('node:vm');
const ctx = { module: undefined, Intl, URLSearchParams };
vm.createContext(ctx);
vm.runInContext(header + body, ctx, { filename: 'Code.gs' });
for (const fn of ['doGet', 'doPost', 'setup']) {
  if (typeof ctx[fn] !== 'function') throw new Error('missing ' + fn + ' in Code.gs');
}
console.log('wrote', path.relative(root, out));
